document.addEventListener('DOMContentLoaded', () => {
    const langBtn = document.getElementById('lang-btn');
    let currentLang = localStorage.getItem('preferredLang') || 'ko';

    function updateContent(lang) {
        // data-translate 속성을 가진 일반 텍스트 번역
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(el => {
            const key = el.getAttribute('data-translate');
            // 안전장치: translations 객체에 해당 키와 언어 데이터가 모두 존재할 때만 교체
            if (translations[key] && translations[key][lang]) {
                el.innerHTML = translations[key][lang];
            }
        });

        // data-translate-alt 속성을 가진 이미지 alt 텍스트 번역
        const altElements = document.querySelectorAll('[data-translate-alt]');
        altElements.forEach(el => {
            const key = el.getAttribute('data-translate-alt');
            if (translations[key] && translations[key][lang]) {
                el.alt = translations[key][lang];
            }
        });

        if (langBtn) {
            langBtn.textContent = lang === 'ko' ? '[ SWITCH LANGUAGE : EN ]' : '[ SWITCH LANGUAGE : KR ]';
        }
        document.documentElement.lang = lang;
        localStorage.setItem('preferredLang', lang);
    }

    if (langBtn) {
        langBtn.addEventListener('click', () => {
            currentLang = currentLang === 'ko' ? 'en' : 'ko';
            updateContent(currentLang);
        });
    }

    // 초기 상태 반영
    updateContent(currentLang);
});